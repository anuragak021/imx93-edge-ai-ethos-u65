#!/usr/bin/env python3
"""Generate stretch_c_app/tests/golden_resize.inc: Pillow's preprocessing of synthetic images.

The C unit test builds the same synthetic images, runs img_preprocess() and compares sampled
output bytes against these Pillow results (tolerance 1 for rounding). Rerun after changing CASES.
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import numpy as np
from PIL import Image

CASES = ((320, 240), (500, 333), (256, 256), (1024, 768), (240, 320))
SHORT_SIDE = 256
CROP = 224
STRIDE = 101  # sample every STRIDE-th output byte


def pattern(width: int, height: int) -> np.ndarray:
    """Must match pattern_byte() in tests/test_imgproc.c."""
    y, x, c = np.mgrid[0:height, 0:width, 0:3]
    return (((x * 2 + y * 3 + c * 50) % 200) + 20).astype(np.uint8)


def preprocess(arr: np.ndarray) -> np.ndarray:
    h, w = arr.shape[:2]
    scale = SHORT_SIDE / min(w, h)
    ow, oh = math.floor(w * scale + 0.5), math.floor(h * scale + 0.5)
    img = Image.fromarray(arr).resize((ow, oh), Image.BILINEAR)
    left, top = (ow - CROP) // 2, (oh - CROP) // 2
    return np.asarray(img.crop((left, top, left + CROP, top + CROP)), dtype=np.uint8)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=Path("stretch_c_app/tests/golden_resize.inc"))
    args = ap.parse_args()

    lines = [
        "/* Generated by tools/gen_resize_golden.py with Pillow. Do not edit. */",
        f"#define GOLDEN_STRIDE {STRIDE}U",
        f"#define GOLDEN_COUNT {math.ceil(CROP * CROP * 3 / STRIDE)}U",
    ]
    names = []
    for w, h in CASES:
        out = preprocess(pattern(w, h)).reshape(-1)[::STRIDE]
        name = f"golden_{w}x{h}"
        names.append((w, h, name))
        body = ", ".join(str(int(v)) for v in out)
        lines.append(f"static const uint8_t {name}[GOLDEN_COUNT] = {{{body}}};")
    lines.append("static const struct { uint32_t w; uint32_t h; const uint8_t *data; } golden_cases[] = {")
    lines += [f"    {{{w}U, {h}U, {n}}}," for w, h, n in names]
    lines.append("};")
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out} ({len(CASES)} cases, Pillow {Image.__version__})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
