#!/usr/bin/env python3
"""Build results/c_app_results.md from results/c_app/* (C app logs) and results/board/infer_*.log.

Compares the C app with the Python app: per-image latency statistics and top-1 agreement.
Run with .venv/bin/python from the imx93 repo root (it imports the wnid table from model/quantize.py).
"""

from __future__ import annotations

import re
import statistics
import sys
from pathlib import Path

RESULTS = Path("results")
C_DIR = RESULTS / "c_app"
PY_DIR = RESULTS / "board"
LINE_RE = re.compile(r"(\S+\.JPEG)\t([\d.]+) ms\ttop1=(.*?)\ttop1_idx=(\d+)\t")
WARMUP_RE = re.compile(r"# warmup_ms=([\d.]+)")

CONFIGS = (
    ("NPU", "c_npu", "infer_npu"),
    ("CPU 1 thread (no XNNPACK)", "c_cpu_1t", None),
    ("CPU 2 threads (no XNNPACK)", "c_cpu_2t", None),
    ("CPU 1 thread, XNNPACK", "c_cpu_1t_xnnpack", "infer_cpu"),
    ("CPU 2 threads, XNNPACK", "c_cpu_2t_xnnpack", None),
)


def parse(path: Path) -> tuple[float, dict[str, tuple[float, str, int]]]:
    warm, rows = float("nan"), {}
    for line in path.read_text().splitlines():
        m = WARMUP_RE.match(line)
        if m:
            warm = float(m.group(1))
        m = LINE_RE.match(line)
        if m:
            rows[m.group(1)] = (float(m.group(2)), m.group(3), int(m.group(4)))
    return warm, rows


def ground_truth() -> dict[str, int]:
    sys.path.insert(0, "model")
    from quantize import WNID_TO_IMAGENET  # needs numpy and Pillow

    return {
        Path(l).name: WNID_TO_IMAGENET[Path(l).parent.name]
        for l in Path("model/sample_list.txt").read_text().split()
    }


def main() -> int:
    truth = ground_truth()
    rows_md, agree_md = [], []
    for label, c_name, py_name in CONFIGS:
        warm, c_rows = parse(C_DIR / f"{c_name}.log")
        lat = [v[0] for v in c_rows.values()]
        acc = sum(v[2] == truth[k] for k, v in c_rows.items()) / len(c_rows)
        rows_md.append(
            f"| {label} | {statistics.median(lat):.2f} | {min(lat):.2f} | {max(lat):.2f} | {warm:.2f} | {len(lat)} | {acc:.2f} |"
        )
        if py_name:
            _, py_rows = parse(PY_DIR / f"{py_name}.log")
            same = sum(c_rows[k][2] == py_rows[k][2] for k in c_rows)
            diffs = [
                f"{k} (C {c_rows[k][1]} / Py {py_rows[k][1]})"
                for k in c_rows
                if c_rows[k][2] != py_rows[k][2]
            ]
            agree_md.append(
                f"- {label}: C and Python top-1 identical on {same} of {len(c_rows)} images"
                + (f"; differing: {'; '.join(diffs)}" if diffs else "")
            )

    env = (C_DIR / "env.txt").read_text()
    md = [
        "# C app results (generated by tools/make_c_results.py from results/c_app/*)",
        "",
        "Per-image `invoke()` latency over the 50 held-out sample images (one inference each, after one warm-up inference).",
        "Fewer samples than the 200-run loop in results.md, so treat the medians as indicative.",
        "",
        "| Config | Median (ms) | Min (ms) | Max (ms) | Warm-up inference (ms) | images | top-1 vs ground truth |",
        "|---|---|---|---|---|---|---|",
        *rows_md,
        "",
        "## C app vs Python app (same model, same images)",
        "",
        *agree_md,
        "",
        "## Build",
        "",
        *[f"- {l}" for l in env.splitlines() if l.startswith(("binary_sha256", "gcc"))],
    ]
    (RESULTS / "c_app_results.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
