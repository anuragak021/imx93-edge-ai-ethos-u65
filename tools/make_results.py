#!/usr/bin/env python3
"""Build results/results.md from the raw logs in results/board and results/vela_summary.txt.

Every number in the generated table is parsed from a saved log or CSV, never typed by hand.
Run from the imx93 repo root:  python3 tools/make_results.py
"""

from __future__ import annotations

import csv
import re
import statistics
import sys
from pathlib import Path

RESULTS = Path("results")
BOARD = RESULTS / "board"
STEADY = "steady"
US_PER_MS = 1000.0

CONFIGS = (
    ("CPU 1 thread, XNNPACK (default)", "cpu_1t_xnnpack"),
    ("CPU 2 threads, XNNPACK (default)", "cpu_2t_xnnpack"),
    ("CPU 1 thread, XNNPACK off", "cpu_1t_noxnnpack"),
    ("CPU 2 threads, XNNPACK off", "cpu_2t_noxnnpack"),
    ("NPU (Ethos-U65, Vela model)", "npu"),
)


def read_csv(name: str) -> tuple[float, list[float]]:
    first, steady = float("nan"), []
    with (BOARD / f"py_{name}.csv").open() as f:
        for row in csv.DictReader(f):
            if row["phase"] == "first":
                first = float(row["latency_ms"])
            elif row["phase"] == STEADY:
                steady.append(float(row["latency_ms"]))
    return first, steady


def bm_avg_ms(name: str) -> tuple[float, float]:
    text = (BOARD / f"bm_{name}.log").read_text()
    first = re.search(r"First inference: (\d+)", text)
    avg = re.search(r"Inference \(avg\): ([\d.]+)", text)
    if not (first and avg):
        raise SystemExit(f"cannot parse benchmark_model log bm_{name}.log")
    return float(first.group(1)) / US_PER_MS, float(avg.group(1)) / US_PER_MS


def top1_by_file(name: str) -> dict[str, tuple[str, int]]:
    out: dict[str, tuple[str, int]] = {}
    for line in (BOARD / f"infer_{name}.log").read_text().splitlines():
        m = re.match(r"(\S+\.JPEG)\t[\d.]+ ms\ttop1=(.*?)\ttop1_idx=(\d+)\ttop5=", line)
        if m:
            out[m.group(1)] = (m.group(2), int(m.group(3)))
    return out


def ground_truth() -> dict[str, int]:
    """Basename -> ImageNet class index, from the wnid folder in model/sample_list.txt."""
    sys.path.insert(0, "model")
    from quantize import WNID_TO_IMAGENET  # needs numpy and Pillow: run with .venv/bin/python

    truth = {}
    for line in Path("model/sample_list.txt").read_text().split():
        path = Path(line)
        truth[path.name] = WNID_TO_IMAGENET[path.parent.name]
    return truth


def main() -> int:
    env = (BOARD / "env.txt").read_text()
    rows, medians = [], {}
    for label, key in CONFIGS:
        first, steady = read_csv(key)
        bm_first, bm_avg = bm_avg_ms(key)
        med = statistics.median(steady)
        medians[key] = med
        rows.append(f"| {label} | {med:.2f} | {first:.2f} | {bm_avg:.2f} | {bm_first:.2f} | {len(steady)} |")

    npu = medians["npu"]
    speed = [
        f"| vs CPU 1 thread, XNNPACK | {medians['cpu_1t_xnnpack'] / npu:.1f}x |",
        f"| vs CPU 2 threads, XNNPACK | {medians['cpu_2t_xnnpack'] / npu:.1f}x |",
        f"| vs CPU 1 thread, XNNPACK off | {medians['cpu_1t_noxnnpack'] / npu:.1f}x |",
        f"| vs CPU 2 threads, XNNPACK off | {medians['cpu_2t_noxnnpack'] / npu:.1f}x |",
    ]

    cpu, nup = top1_by_file("cpu"), top1_by_file("npu")
    same = sum(1 for k in cpu if nup.get(k) == cpu[k])
    diffs = [f"{k}: cpu={cpu[k][0]} npu={nup[k][0]}" for k in cpu if nup.get(k) != cpu[k]]
    truth = ground_truth()
    acc_cpu = sum(cpu[k][1] == truth[k] for k in cpu) / len(cpu)
    acc_npu = sum(nup[k][1] == truth[k] for k in nup) / len(nup)

    vela = (BOARD / "vela_summary.txt").read_text()
    remoteproc = (BOARD / "remoteproc_state.txt").read_text().strip().replace("\n", "; ")
    cpu_ops = re.search(r"CPU operators = (\d+) \(([\d.]+)%\)", vela)
    npu_ops = re.search(r"NPU operators = (\d+) \(([\d.]+)%\)", vela)
    est = re.search(r"Batch Inference time\s+([\d.]+) ms", vela)
    kv = dict(l.split("=", 1) for l in env.splitlines() if re.match(r"^[a-z0-9_]+=", l))

    md = [
        "# Results (generated by tools/make_results.py from results/board/*)",
        "",
        "Latency per inference in ms, MobileNetV2 224x224 int8, batch 1, 200 steady-state runs after 10 warm-up runs.",
        "'Median' and 'first' come from `bench.py` (per-run CSV). 'benchmark_model' columns are the TFLite tool's own average and first inference.",
        "",
        "| Config | Median (ms) | First run (ms) | benchmark_model avg (ms) | benchmark_model first (ms) | runs |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        "Speedup of the NPU median over each CPU median:",
        "",
        "| Baseline | Speedup |",
        "|---|---|",
        *speed,
        "",
        "## Model size",
        "",
        f"- int8 TFLite before Vela: {kv['model_cpu_bytes']} bytes (sha256 {kv['sha256_cpu_model']})",
        f"- after Vela (NPU model): {kv['model_npu_bytes']} bytes (sha256 {kv['sha256_npu_model']})",
        "",
        "## Vela operator placement (results/board/vela_summary.txt)",
        "",
        f"- NPU operators: {npu_ops.group(1)} ({npu_ops.group(2)}%), CPU operators: {cpu_ops.group(1)} ({cpu_ops.group(2)}%)",
        f"- Vela's own cycle-model estimate: {est.group(1)} ms per inference (an estimate, not a measurement)",
        "",
        "## CPU vs NPU classification agreement (50 held-out images)",
        "",
        f"- top-1 identical on {same} of {len(cpu)} images",
        *([f"- differences: {'; '.join(diffs)}"] if diffs else []),
        f"- board top-1 vs ground truth (1000-way argmax): CPU {acc_cpu:.2f}, NPU {acc_npu:.2f}",
        "",
        "## Board state during the run",
        "",
        (
            "- cpufreq sysfs not exposed on this BSP, CPU clock/governor not recorded"
            if kv.get("cpu_governor", "").startswith("cat:")
            else f"- cpu governor: {kv.get('cpu_governor')}, cur/max kHz: {kv.get('cpu_cur_khz')}/{kv.get('cpu_max_khz')}"
        ),
        f"- tflite_runtime {kv.get('tflite_runtime')}, vela {kv.get('vela')}",
        f"- remoteproc / dmesg after the NPU runs: {remoteproc}",
    ]
    (RESULTS / "results.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
